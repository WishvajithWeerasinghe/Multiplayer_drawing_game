package com.example.draw.model;

import jakarta.persistence.*;
import java.time.Instant;
import java.util.UUID;

/** One finished pen stroke. Points are stored as a JSON array string: [{"x":1,"y":2},...] */
@Entity
@Table(name = "strokes", indexes = @Index(columnList = "boardId, createdAt"))
public class Stroke {
    @Id
    private String id; // generated by the client (UUID)

    @Column(nullable = false)
    private UUID boardId;

    private String userId;
    private String color;
    private int size;

    @Column(columnDefinition = "text", nullable = false)
    private String points;

    @Column(nullable = false)
    private Instant createdAt = Instant.now();

    public Stroke() {}

    public String getId() { return id; }
    public void setId(String id) { this.id = id; }
    public UUID getBoardId() { return boardId; }
    public void setBoardId(UUID boardId) { this.boardId = boardId; }
    public String getUserId() { return userId; }
    public void setUserId(String userId) { this.userId = userId; }
    public String getColor() { return color; }
    public void setColor(String color) { this.color = color; }
    public int getSize() { return size; }
    public void setSize(int size) { this.size = size; }
    public String getPoints() { return points; }
    public void setPoints(String points) { this.points = points; }
    public Instant getCreatedAt() { return createdAt; }
}
